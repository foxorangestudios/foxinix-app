/**
 * Traduce `str` al idioma activo (si hay traducción) e interpola `{clave}`.
 * En español devuelve el texto tal cual, así que se puede usar sin miedo.
 */
export function t(str, vars) {
  let s = (store.lang === 'en' && EN[str]) ? EN[str] : str;
  if (vars) {
    for (const k in vars) s = s.split('{' + k + '}').join(String(vars[k]));
  }
  return s;
}

/** Cambia y persiste el idioma de la interfaz (es | en). */
export function setLang(lang) {
  const l = lang === 'en' ? 'en' : 'es';
  store.lang = l;
  document.documentElement.setAttribute('lang', l);
  try { localStorage.setItem('fm.lang', l); } catch (e) {}
}

